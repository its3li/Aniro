// Phosphor MIT icon geometry, with only weights actually used by Aniro.
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { readFile, writeFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

async function files(dir) {
  const result = [];
  for(const item of await readdir(dir,{withFileTypes:true})) {
    if(item.isDirectory()) result.push(...await files(dir+'/'+item.name));
    else if(item.name.endsWith('.tsx') && item.name !== 'interface-icons.tsx') result.push(dir+'/'+item.name);
  }
  return result;
}
const targets = await files('src');
const names = new Set();
const pattern = /import \{ (\w+Icon) as (\w+) \} from '@phosphor-icons\/react\/dist\/csr\/(\w+)';/g;
for(const file of targets) {
  const source = await readFile(file,'utf8');
  for(const match of source.matchAll(pattern)) {
    names.add(match[3]);
  }
}
try {
  const existing = await readFile('src/components/icons/interface-icons.tsx','utf8');
  for(const match of existing.matchAll(/export const (\w+)Icon/g)) names.add(match[1]);
} catch (error) { if (error.code !== 'ENOENT') throw error; }
let output = "'use client';\n// Generated by scripts/generate-interface-icons.mjs. Phosphor icons: MIT.\nimport { forwardRef, type SVGProps, type ReactNode } from 'react';\nexport type IconProps = SVGProps<SVGSVGElement> & { weight?: 'regular' | 'duotone' | 'fill'; size?: number | string };\nfunction createIcon(bodies: Partial<Record<NonNullable<IconProps['weight']>, ReactNode>>) {\n  return forwardRef<SVGSVGElement, IconProps>(function InterfaceIcon({weight='regular',size=24,...props},ref) {\n    return <svg ref={ref} width={size} height={size} viewBox=\"0 0 256 256\" fill=\"currentColor\" aria-hidden=\"true\" {...props}>{bodies[weight] ?? bodies.regular}</svg>;\n  });\n}\n";
const jsx = markup => markup.replace(/<svg>|<\/svg>/g,'').replace(/\b([a-z]+)-([a-z]+)=/g,(_,a,b)=>a+b[0].toUpperCase()+b.slice(1)+'=');
for(const name of [...names].sort()) {
  const {default:weights} = await import(pathToFileURL(resolve('node_modules/@phosphor-icons/react/dist/defs/'+name+'.es.js')));
  const used = ['regular'];
  if(['BookOpen','Compass','HandsPraying','HouseLine','SlidersHorizontal'].includes(name)) used.push('duotone');
  if(['Play','Pause','SkipBack','SkipForward'].includes(name)) used.push('fill');
  const bodies = used.map(weight=>weight+':<>'+jsx(renderToStaticMarkup(createElement('svg',null,weights.get(weight))))+'</>');
  output += 'export const '+name+'Icon = /* @__PURE__ */ createIcon({'+bodies.join(',')+'});\n';
}
await writeFile('src/components/icons/interface-icons.tsx',output);
for(const file of targets) {
  const source = await readFile(file,'utf8');
  const updated = source.replace(pattern,(_,name,alias)=>"import { "+name+" as "+alias+" } from '@/components/icons/interface-icons';");
  if(source!==updated) await writeFile(file,updated);
}
await writeFile('src/components/icons/Phosphor-LICENSE.txt',await readFile('node_modules/@phosphor-icons/react/LICENSE','utf8'));

// Keep Android launcher-widget symbols in the same family.
const widgets = { fajr:'SunHorizon', prayer:'SunHorizon', ishraq:'CloudSun', dhuhr:'Sun', asr:'SunDim', maghrib:'SunHorizon', isha:'MoonStars' };
for(const [resource,name] of Object.entries(widgets)) {
  const {default:weights}=await import(pathToFileURL(resolve('node_modules/@phosphor-icons/react/dist/defs/'+name+'.es.js')));
  const markup=renderToStaticMarkup(createElement('svg',null,weights.get('regular')));
  const paths=[...markup.matchAll(/<path[^>]* d="([^"]+)"/g)].map(match=>'<path android:fillColor="#FFB52E" android:pathData="'+match[1]+'" />');
  if(!paths.length) throw new Error('Missing widget icon: '+name);
  await writeFile('android/app/src/main/res/drawable/ic_'+resource+'.xml','<?xml version="1.0" encoding="utf-8"?>\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="256" android:viewportHeight="256">\n'+paths.join('\n')+'\n</vector>\n');
}
